#!/usr/bin/env python3
"""
make_table2.py — Table II (internal comparison of forecasters), computed entirely at the
PATIENT level from the saved unified-evaluation outputs: every metric is averaged over each
patient's pairs first, then over the 81 patients. Calibration error and 90% coverage use
patient-averaged coverage curves, exactly as Fig. 2 and the pre-registered external analysis.

Calibrated quantities use the cross-fitted temperature of aggregate_unified.prepare(); the
temperature of each pair is recovered from its calibrated brain CRPS (checked below).

Usage:  python make_table2.py        -> LaTeX rows for Table II + table2_values.json
"""
import os, sys, json
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import aggregate_unified as AG

EVAL = os.path.join(HERE, "runs", "eval_unified")


def pmean(recs, key):
    vals = [v for _, v in AG.by_patient(recs, key).values()]
    return float(np.nanmean(vals)) if vals else float("nan")


def calibration(run):
    """Patient-level calibration error and 90% coverage, raw (T=1) and calibrated (cross-fitted T)."""
    Tg, ideal, nom = (np.asarray(run[k], float) for k in ("Tg", "ideal", "nominal"))
    cov, crps = np.asarray(run["arrs"]["cov_brain"]), np.asarray(run["arrs"]["crps_brain"])
    i1, i90 = int(np.argmin(np.abs(Tg - 1.0))), int(np.argmin(np.abs(nom - 0.9)))
    raw, cal, worst, Ts = {}, {}, 0.0, []
    for r in run["recs"]:
        row = r["_row"]
        ic = int(np.nanargmin(np.abs(crps[row] - r["crps_cal_brain"])))
        worst = max(worst, abs(float(crps[row, ic]) - float(r["crps_cal_brain"])))
        Ts.append(float(Tg[ic]))
        raw.setdefault(r["patient"], []).append(cov[row, i1])
        cal.setdefault(r["patient"], []).append(cov[row, ic])
    out = {}
    for lab, d in (("raw", raw), ("cal", cal)):
        P = np.stack([np.nanmean(np.stack(v), 0) for v in d.values()])
        out[f"calerr_{lab}"] = float(np.mean(np.abs(np.nanmean(P, 0) - ideal)))
        out[f"cov90_{lab}"] = float(np.nanmean(P[:, i90]))
    out.update(T_range=[min(Ts), max(Ts)], crps_match_max_err=worst, ideal90=float(ideal[i90]), n_patients=len(raw))
    return out


def main():
    runs = {n: AG.prepare(n, os.path.join(EVAL, n), "brain") for n in ("flow", "ddpm", "ar1", "damped", "clim")}
    F = runs["flow"]["recs"]
    rows = []

    def add(label, recs, suffix, dist=None, raw=False):
        row = dict(label=label,
                   whole=pmean(recs, f"mse_whole_{suffix}"), brain=pmean(recs, f"mse_brain_{suffix}"),
                   roi=pmean(recs, f"mse_roi_{suffix}"), cos=pmean(recs, f"cos_roi_{suffix}"))
        if dist is not None:
            c = calibration(dist)
            tag = "raw" if raw else "cal"
            row.update(bcrps=pmean(recs, f"crps_{tag}_brain"), rcrps=pmean(recs, f"crps_{tag}_roi"),
                       calerr=c[f"calerr_{tag}"], cov90=c[f"cov90_{tag}"], _check=c)
        rows.append(row)

    add("Persistence", F, "copy")
    add("Linear extrapolation$^{a}$", [r for r in F if r.get("has_prev")], "linear")
    add("Climatology", runs["clim"]["recs"], "model", runs["clim"])
    add("Damped persistence", runs["damped"]["recs"], "model", runs["damped"])
    add("Voxel-wise AR(1)", runs["ar1"]["recs"], "model", runs["ar1"])
    add("Diffusion$^{b}$", runs["ddpm"]["recs"], "model", runs["ddpm"])
    add("Bio-SSM-Flow (raw)$^{c}$", F, "model", runs["flow"], raw=True)
    add("Bio-SSM-Flow", F, "model", runs["flow"])

    # also the raw diffusion calibration (used in the text)
    ddpm_c = calibration(runs["ddpm"])

    cols = [("whole", 3, min), ("brain", 3, min), ("roi", 3, min), ("cos", 3, max),
            ("bcrps", 3, min), ("rcrps", 3, min), ("calerr", 4, min), ("cov90", 3, "ideal")]
    ideal90 = rows[-1]["_check"]["ideal90"]
    best = {}
    for key, _, rule in cols:
        vals = [(i, r[key]) for i, r in enumerate(rows) if key in r and np.isfinite(r[key])]
        if rule == "ideal":
            target = min(abs(v - ideal90) for _, v in vals)
            best[key] = {i for i, v in vals if abs(abs(v - ideal90) - target) < 5e-4}
        else:
            target = rule(v for _, v in vals)
            best[key] = {i for i, v in vals if abs(v - target) < 5e-4}

    print("% ---- Table II rows (patient-level; generated by make_table2.py) ----")
    for i, r in enumerate(rows):
        cells = []
        for key, dec, _ in cols:
            if key not in r:
                cells.append("--"); continue
            s = f"{r[key]:.{dec}f}"
            cells.append(f"\\textbf{{{s}}}" if i in best[key] else s)
        print(f"{r['label']:28s} & " + " & ".join(cells) + " \\\\")

    fl = rows[-1]["_check"]
    print("\n% ---- numbers for the text (Section V-B) ----")
    print(f"Bio-SSM-Flow calibration error: raw {fl['calerr_raw']:.4f} -> calibrated {fl['calerr_cal']:.4f} "
          f"({100 * (1 - fl['calerr_cal'] / fl['calerr_raw']):.0f}% reduction)")
    print(f"Bio-SSM-Flow 90% coverage: raw {fl['cov90_raw']:.3f} -> calibrated {fl['cov90_cal']:.3f} (ideal {ideal90:.3f})")
    print(f"Diffusion calibration error: raw {ddpm_c['calerr_raw']:.4f} -> calibrated {ddpm_c['calerr_cal']:.4f}")
    refs = [r for r in rows if r["label"] in ("Climatology", "Damped persistence", "Voxel-wise AR(1)")]
    print(f"Reference forecasts, calibrated calibration error: {min(r['calerr'] for r in refs):.4f}-{max(r['calerr'] for r in refs):.4f}")
    print("\n% ---- checks ----")
    for r in rows:
        if "_check" in r:
            c = r["_check"]
            print(f"{r['label']:28s} T {c['T_range'][0]:.2f}-{c['T_range'][1]:.2f} | CRPS match error {c['crps_match_max_err']:.1e} | patients {c['n_patients']}")
    with open(os.path.join(HERE, "table2_values.json"), "w") as f:
        json.dump(dict(rows=[{k: v for k, v in r.items()} for r in rows], diffusion_calibration=ddpm_c,
                       ideal90=ideal90), f, indent=1, default=float)
    print("\n[saved] table2_values.json")


if __name__ == "__main__":
    main()
